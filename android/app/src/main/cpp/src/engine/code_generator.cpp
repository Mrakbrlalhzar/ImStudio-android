#include <sstream>

extern ImStudio::BufferWindow g_Buffer;  // defined in buffer_accessor.cpp

namespace imstudio::engine {

std::string generate_full_code() {
    std::ostringstream out;
    out << "// Generated by ImStudio (Android)\n";
    out << "// Upstream: Raais/ImStudio\n\n";
    out << "#include \"imgui.h\"\n\n";

    for (auto& obj : g_Buffer.objects) {
        if (obj.type == "checkbox") {
            out << "static bool c1" << obj.id << " = false;\n";
        } else if (obj.type == "radio") {
            out << "static bool r1" << obj.id << " = false;\n";
        } else if (obj.type == "combo" || obj.type == "listbox") {
            out << "static const char* items" << obj.id
                << "[] = { \"Item 1\", \"Item 2\", \"Item 3\" };\n";
        } else if (obj.type == "sliderfloat" || obj.type == "dragfloat") {
            out << "static float f1" << obj.id << " = 0.0f;\n";
        } else if (obj.type == "sliderint" || obj.type == "dragint") {
            out << "static int i1" << obj.id << " = 0;\n";
        } else if (obj.type == "textinput") {
            out << "static char buf" << obj.id << "[128] = \"\";\n";
        } else if (obj.type == "inputint") {
            out << "static int in1" << obj.id << " = 0;\n";
        } else if (obj.type == "inputfloat") {
            out << "static float inf1" << obj.id << " = 0.0f;\n";
        }
    }
    out << "\nvoid RenderUI() {\n";

    for (auto& obj : g_Buffer.objects) {
        std::string snippet;
        ImStudio::Recreate(obj, &snippet, g_Buffer.staticlayout);
        out << snippet;
    }

    out << "}\n";
    return out.str();
}

} // namespace imstudio::engine
